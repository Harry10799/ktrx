#!/usr/bin/env bash
# Capture a real KTRX trace-url --aws run against an existing Kubernetes/AWS setup.
# Requirements: Bash, Go, kubectl, a reachable cluster, and AWS credentials for ELBv2.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

BINARY="${KTRX_BINARY:-$ROOT_DIR/ktrx}"
DOC="$ROOT_DIR/docs/AWS_DEMO.md"
URL="${KTRX_AWS_DEMO_URL:-}"
NAMESPACE="${KTRX_AWS_DEMO_NAMESPACE:-default}"
AWS_REGION="${KTRX_AWS_DEMO_REGION:-}"
KUBECONFIG_ARGS=()

if [[ -z "$URL" ]]; then
  echo "Set KTRX_AWS_DEMO_URL to an HTTP(S) URL routed by an Ingress/Gateway with a TargetGroupBinding." >&2
  echo "Example: KTRX_AWS_DEMO_URL=https://api.example.com/health KTRX_AWS_DEMO_NAMESPACE=production bash scripts/generate-aws-demo.sh" >&2
  exit 2
fi

if [[ -n "${KUBECONFIG:-}" ]]; then
  KUBECONFIG_ARGS+=(--kubeconfig "$KUBECONFIG")
fi

TMP_DIR="$(mktemp -d)"
cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT

mkdir -p "$(dirname "$DOC")"
: > "$DOC"

cat >> "$DOC" <<EOF
# KTRX AWS target-health demo

This file is generated by `scripts/generate-aws-demo.sh`.

- Generated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')
- Kubernetes context: $(kubectl config current-context 2>/dev/null || echo 'unknown')
- Namespace scope: `$NAMESPACE`
- URL: `$URL`
- AWS region override: `${AWS_REGION:-not set (use TargetGroupBinding ARN region)}`
- AWS mode: **live** — KTRX uses its standard AWS SDK credential chain and calls read-only ELBv2 `DescribeTargetHealth`.
- The script creates or changes no Kubernetes or AWS resources.

> This report can contain internal hostnames, IP addresses, target-group ARNs and workload names. Review and redact it before publishing.
> The AWS section is meaningful only when the URL matches a Kubernetes route whose backend has an AWS Load Balancer Controller TargetGroupBinding.
> A missing binding, unavailable CRD/RBAC, missing AWS credentials or denied IAM permission is captured as KTRX output; the script does not fabricate target-health data.
EOF

run_section() {
  local title="$1"
  shift
  local output_file status
  output_file="$(mktemp "$TMP_DIR/command.XXXXXX")"
  {
    printf '\n## %s\n\n' "$title"
    printf 'Command:\n\n```bash\n$'
    printf ' %q' "$@"
    printf '\n```\n\nOutput:\n\n```text\n'
  } >> "$DOC"

  if "$@" >"$output_file" 2>&1; then
    status=0
  else
    status=$?
  fi

  sed -E 's/\x1B\[[0-9;]*[[:alpha:]]//g' "$output_file" >> "$DOC"
  printf '\n[exit status: %s]\n' "$status" >> "$DOC"
  printf '```\n' >> "$DOC"
  rm -f "$output_file"
  return 0
}

run_required() {
  if ! run_section "$@"; then
    echo "A required AWS demo step failed. See $DOC" >&2
    exit 1
  fi
}

run_required "Build KTRX" go build -o "$BINARY" ./cmd/ktrx
run_section "Kubernetes TargetGroupBindings in scope" kubectl get targetgroupbindings.elbv2.k8s.aws -n "$NAMESPACE" -o wide
run_section "Baseline URL trace (AWS integration disabled)" "$BINARY" trace-url "$URL" -n "$NAMESPACE" "${KUBECONFIG_ARGS[@]}" --output terminal
run_section "Baseline URL trace (JSON)" "$BINARY" trace-url "$URL" -n "$NAMESPACE" "${KUBECONFIG_ARGS[@]}" --output json

AWS_ARGS=(--aws)
if [[ -n "$AWS_REGION" ]]; then
  AWS_ARGS+=(--aws-region "$AWS_REGION")
fi

run_section "URL trace with live AWS target health (terminal)" "$BINARY" trace-url "$URL" -n "$NAMESPACE" "${KUBECONFIG_ARGS[@]}" "${AWS_ARGS[@]}" --output terminal
run_section "URL trace with live AWS target health (JSON)" "$BINARY" trace-url "$URL" -n "$NAMESPACE" "${KUBECONFIG_ARGS[@]}" "${AWS_ARGS[@]}" --output json
run_section "URL trace with live AWS target health (Markdown)" "$BINARY" trace-url "$URL" -n "$NAMESPACE" "${KUBECONFIG_ARGS[@]}" "${AWS_ARGS[@]}" --output markdown

cat >> "$DOC" <<'EOF'

## Reproduce this report

Set the URL to a real host/path routed by an Ingress or Gateway whose Service backend is associated with an AWS TargetGroupBinding:

```bash
KTRX_AWS_DEMO_URL=https://api.example.com/health \
KTRX_AWS_DEMO_NAMESPACE=production \
bash scripts/generate-aws-demo.sh
```

Optionally override the target-group region:

```bash
KTRX_AWS_DEMO_URL=https://api.example.com/health \
KTRX_AWS_DEMO_NAMESPACE=production \
KTRX_AWS_DEMO_REGION=ap-south-1 \
bash scripts/generate-aws-demo.sh
```

KTRX uses the AWS SDK standard credential chain (for example, an AWS profile, environment credentials, web identity or an attached role). The required read-only IAM action for this integration is `elasticloadbalancing:DescribeTargetHealth`.

This is a live integration capture, not the offline fixture test. For a no-AWS/no-cluster code-path test, run `bash scripts/test-aws-mock.sh`.
EOF

echo "KTRX AWS demo report generated: $DOC"
