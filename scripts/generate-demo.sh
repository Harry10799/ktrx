#!/usr/bin/env bash
# Generate a reproducible, command-by-command KTRX demo report for the README.
# Requirements: Bash, Go, kubectl, and a reachable Kubernetes cluster.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

BINARY="${KTRX_BINARY:-$ROOT_DIR/ktrx}"
DOC="$ROOT_DIR/docs/DEMO.md"
NAMESPACE="${KTRX_DEMO_NAMESPACE:-ktrx-demo}"
CREATED_NAMESPACE=0

if ! kubectl cluster-info >/dev/null 2>&1; then
  echo "Kubernetes is not reachable through the current kubectl context." >&2
  echo "Configure a valid kubeconfig/context, then rerun: bash scripts/generate-demo.sh" >&2
  exit 1
fi

TMP_DIR="$(mktemp -d)"

cleanup() {
  if [[ "$CREATED_NAMESPACE" -eq 1 && "${KEEP_DEMO:-0}" != "1" ]]; then
    kubectl delete namespace "$NAMESPACE" --wait=false >/dev/null 2>&1 || true
  fi
  rm -rf "$TMP_DIR"
}
trap cleanup EXIT

mkdir -p "$(dirname "$DOC")"
: > "$DOC"

cat >> "$DOC" <<EOF
# KTRX live demo

This file is generated by \`scripts/generate-demo.sh\`.

- Generated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')
- Kubernetes context: $(kubectl config current-context 2>/dev/null || echo 'unknown')
- Namespace: \`$NAMESPACE\`
- Commands are executed against a temporary demo workload. Output below is captured from the current cluster.
- The script deletes the demo namespace when it finishes. Set \`KEEP_DEMO=1\` to keep it for inspection.

> Some checks depend on cluster RBAC, installed Ingress controllers, and container utilities. Their actual results are captured rather than assumed.
> The reference workload has a readiness probe; liveness/startup probes are intentionally omitted. The candidate uses the same container name and settings, changing only its image.
> Transient FailedScheduling Events from initial single-node scheduling are cleared after the reference Deployment is ready, so the report focuses on current workload evidence.
EOF

run_section() {
  local title="$1"
  shift
  local output_file status
  output_file="$(mktemp "$TMP_DIR/command.XXXXXX")"
  {
    printf '\n## %s\n\n' "$title"
    printf 'Command:\n\n```bash\n$'
    printf ' %q' "$@"
    printf '\n```\n\nOutput:\n\n```text\n'
  } >> "$DOC"

  if "$@" >"$output_file" 2>&1; then
    status=0
  else
    status=$?
  fi

  # Strip ANSI color sequences so the generated Markdown stays readable.
  sed -E 's/\x1B\[[0-9;]*[[:alpha:]]//g' "$output_file" >> "$DOC"
  if [[ "$status" -ne 0 ]]; then
    printf '\n[command exited with status %s]\n' "$status" >> "$DOC"
  fi
  printf '```\n' >> "$DOC"
  rm -f "$output_file"
  return "$status"
}

run_required() {
  if ! run_section "$@"; then
    echo "A required demo step failed. See $DOC" >&2
    exit 1
  fi
}

run_required "Build KTRX" go build -o "$BINARY" ./cmd/ktrx
run_section "KTRX top-level help" "$BINARY" --help || true
run_section "Pod inspection help" "$BINARY" pod --help || true
run_section "Cluster preflight help" "$BINARY" doctor --help || true
run_section "Runtime network check help" "$BINARY" netcheck --help || true
run_section "Pod comparison help" "$BINARY" compare --help || true

if kubectl get namespace "$NAMESPACE" >/dev/null 2>&1; then
  echo "Namespace '$NAMESPACE' already exists. Choose another with KTRX_DEMO_NAMESPACE." >&2
  exit 1
fi
run_required "Create isolated demo namespace" kubectl create namespace "$NAMESPACE"
CREATED_NAMESPACE=1

cat > "$TMP_DIR/demo.yaml" <<EOF
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ktrx-demo-nginx
  namespace: $NAMESPACE
spec:
  replicas: 2
  selector:
    matchLabels:
      app: ktrx-demo-nginx
  template:
    metadata:
      labels:
        app: ktrx-demo-nginx
    spec:
      containers:
        - name: nginx
          image: nginx:1.27
          ports:
            - name: http
              containerPort: 80
          readinessProbe:
            httpGet:
              path: /
              port: http
            initialDelaySeconds: 2
            periodSeconds: 5
          resources:
            requests:
              cpu: 25m
              memory: 32Mi
            limits:
              cpu: 250m
              memory: 128Mi
---
apiVersion: v1
kind: Service
metadata:
  name: ktrx-demo-nginx
  namespace: $NAMESPACE
spec:
  selector:
    app: ktrx-demo-nginx
  ports:
    - name: http
      port: 80
      targetPort: http
EOF

run_required "Create demo Deployment and Service" kubectl apply -f "$TMP_DIR/demo.yaml"
run_required "Wait for Deployment rollout" kubectl rollout status deployment/ktrx-demo-nginx -n "$NAMESPACE" --timeout=120s
run_section "Clear transient scheduling Events after successful rollout" kubectl delete events -n "$NAMESPACE" --field-selector reason=FailedScheduling --ignore-not-found || true
run_required "List demo Pods" kubectl get pods -n "$NAMESPACE" -o wide

REF_POD="$(kubectl get pods -n "$NAMESPACE" -l app=ktrx-demo-nginx -o jsonpath='{.items[0].metadata.name}')"
if [[ -z "$REF_POD" ]]; then
  echo "Could not find a reference Pod in namespace $NAMESPACE" >&2
  exit 1
fi

run_section "Inspect a Pod (terminal)" "$BINARY" "$REF_POD" -n "$NAMESPACE" --no-color || true
run_section "Inspect a Pod (JSON)" "$BINARY" "$REF_POD" -n "$NAMESPACE" --output json || true
run_section "Inspect a Pod (Markdown)" "$BINARY" "$REF_POD" -n "$NAMESPACE" --output markdown || true
run_section "Inspect every Deployment replica" "$BINARY" deploy/ktrx-demo-nginx -n "$NAMESPACE" --all --no-color || true

run_section "Kubernetes permission preflight" "$BINARY" doctor -n "$NAMESPACE" --include-netcheck --no-color || true
run_section "Kubernetes permission preflight (JSON)" "$BINARY" doctor -n "$NAMESPACE" --include-netcheck --output json || true

run_required "Create an in-cluster toolbox Pod" kubectl run ktrx-demo-tools --image=busybox:1.36 --restart=Never -n "$NAMESPACE" --command -- sleep 3600
run_required "Wait for toolbox Pod" kubectl wait --for=condition=Ready pod/ktrx-demo-tools -n "$NAMESPACE" --timeout=90s
run_section "Runtime DNS and TCP checks" "$BINARY" netcheck ktrx-demo-tools -n "$NAMESPACE" --dns "ktrx-demo-nginx" --tcp "ktrx-demo-nginx:80" --no-color || true
run_section "Runtime checks (JSON)" "$BINARY" netcheck ktrx-demo-tools -n "$NAMESPACE" --dns "ktrx-demo-nginx" --tcp "ktrx-demo-nginx:80" --output json || true

cat > "$TMP_DIR/candidate.yaml" <<EOF
apiVersion: v1
kind: Pod
metadata:
  name: ktrx-demo-candidate
  namespace: $NAMESPACE
  labels:
    app: ktrx-demo-nginx
spec:
  containers:
    - name: nginx
      image: nginx:1.26
      ports:
        - name: http
          containerPort: 80
      readinessProbe:
        httpGet:
          path: /
          port: http
        initialDelaySeconds: 2
        periodSeconds: 5
      resources:
        requests:
          cpu: 25m
          memory: 32Mi
        limits:
          cpu: 250m
          memory: 128Mi
EOF

run_required "Create candidate Pod with matching configuration and a different image" kubectl apply -f "$TMP_DIR/candidate.yaml"
run_required "Wait for candidate Pod" kubectl wait --for=condition=Ready pod/ktrx-demo-candidate -n "$NAMESPACE" --timeout=90s
run_section "Clear transient scheduling Events after candidate is ready" kubectl delete events -n "$NAMESPACE" --field-selector reason=FailedScheduling --ignore-not-found || true
run_section "Compare reference Pod with candidate (terminal)" "$BINARY" compare "$REF_POD" ktrx-demo-candidate -n "$NAMESPACE" --no-color || true
run_section "Compare reference Pod with candidate (JSON)" "$BINARY" compare "$REF_POD" ktrx-demo-candidate -n "$NAMESPACE" --output json || true

cat >> "$DOC" <<EOF

## Cleanup

The script removes namespace \`$NAMESPACE\` automatically when it exits, unless \`KEEP_DEMO=1\` was set.

To reproduce this report:

```bash
bash scripts/generate-demo.sh
```

To retain the temporary resources for manual inspection:

```bash
KEEP_DEMO=1 bash scripts/generate-demo.sh
```
EOF

if [[ "${KEEP_DEMO:-0}" == "1" ]]; then
  echo "Demo namespace retained: $NAMESPACE"
else
  if run_section "Delete temporary demo namespace" kubectl delete namespace "$NAMESPACE" --wait=false; then
    CREATED_NAMESPACE=0
  fi
fi

echo "KTRX demo report generated: $DOC"
