#!/usr/bin/env bash
# Generate a reproducible AWS target-health report from the checked-in mock fixture.
# No Kubernetes cluster, AWS account, credentials or AWS API calls are required.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

DOC="$ROOT_DIR/docs/AWS_MOCK_DEMO.md"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

mkdir -p "$(dirname "$DOC")"
cat > "$DOC" <<EOF
# KTRX AWS target-health mock demo

This file is generated by scripts/generate-aws-mock-demo.sh.

- Generated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')
- Source fixture: internal/cli/testdata/aws_target_health_mock.json
- Data source: **mocked** ELBv2 DescribeTargetHealth response.
- AWS API calls: **none**.
- Kubernetes cluster or kubeconfig: **not required**.
- Expected result: one healthy target, one unhealthy target (Target.Timeout), Pod-IP correlation, overall WARN.

> This report demonstrates KTRX's parsing, correlation, verdict and output formatting using a fake AWS SDK client. It is not output from a live ktrx trace-url --aws invocation.

EOF

if KTRX_AWS_MOCK_DEMO=1 go test ./internal/cli -run '^TestAWSMockTargetHealthScenario$' -count=1 -v >"$TMP_DIR/output.txt" 2>&1; then
  cat "$TMP_DIR/output.txt" >> "$DOC"
else
  cat "$TMP_DIR/output.txt" >&2
  echo "AWS mock demo generation failed; see test output above." >&2
  exit 1
fi

cat >> "$DOC" <<'EOF'

## What this demonstrates

1. KTRX receives a simulated ELBv2 target-health response.
2. It reads target state, reason and description.
3. It correlates IP-type targets with Pod IP addresses.
4. It applies the AWS target-health verdict rule: mixed healthy/unhealthy targets produce WARN.
5. It renders the report as terminal text, JSON and Markdown.

To regenerate:

```bash
bash scripts/generate-aws-mock-demo.sh
```

For the live AWS integration capture (requires a real cluster, TargetGroupBinding and AWS credentials), see scripts/generate-aws-demo.sh.
EOF

echo "KTRX AWS mock demo report generated: $DOC"
